#!/usr/bin/env python3
"""Generate docs/tools.md from home/.chezmoidata/packages.yaml and docs/tool-descriptions.yaml.

Usage:
  scripts/gen-tools-doc.py           write docs/tools.md
  scripts/gen-tools-doc.py --check   fail when a tool has no description, a description is unused,
                                     or docs/tools.md is out of date
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ROOT / "home/.chezmoidata/packages.yaml"
DESCRIPTIONS = ROOT / "docs/tool-descriptions.yaml"
OUTPUT = ROOT / "docs/tools.md"
MACHINES = ("common", "athena", "nabla-mac-raphael")
WHERE = {"common": "both Macs", "athena": "athena", "nabla-mac-raphael": "nabla-mac-raphael"}


def load_yaml(path, expr="."):
    out = subprocess.run(["yq", "-o=json", expr, str(path)], check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def strip_version(entry):
    """java@oracle-graalvm-21.0.7 -> java; npm:@scope/pkg stays as it is."""
    match = re.search(r"@([^@/:]+)$", entry)
    return entry[: match.start()] if match else entry


def collect(section, key=lambda x: x):
    """Return {entry: [machines]} for a {common, athena, nabla-mac-raphael} section of lists."""
    found = {}
    for machine in MACHINES:
        for item in section.get(machine) or []:
            found.setdefault(key(item), []).append(machine)
    return found


def collect_mas(section):
    found = {}
    for machine in MACHINES:
        for name in (section.get(machine) or {}).values():
            found.setdefault(name, []).append(machine)
    return found


def where(machines):
    return ", ".join(WHERE[m] for m in machines)


def main():
    check = "--check" in sys.argv[1:]
    pk = load_yaml(PACKAGES, ".packages")
    desc = load_yaml(DESCRIPTIONS)

    # (heading, description group, {display entry: machines}, key for the description)
    sections = [
        ("mise tools", "mise", collect(pk["mise"]), strip_version),
        ("Homebrew taps", "taps", collect(pk["brew"]["taps"]), lambda x: x),
        ("Homebrew formulae", "formulae", collect(pk["brew"]["formulae"]), lambda x: x),
        ("Homebrew casks (apps and fonts)", "casks", collect(pk["brew"]["casks"]), lambda x: x),
        ("App Store apps (mas)", "mas", collect_mas(pk["mas"]), lambda x: x),
        ("GitHub CLI extensions", "gh_extensions", collect(pk["gh_extensions"], key=lambda x: x["repo"]), lambda x: x),
        ("Agent skills for Claude Code", "gh_skills", collect(pk["gh_skills"], key=lambda x: x["skill"]), lambda x: x),
        ("rustup components", "rustup", collect(pk["rustup_components"]), lambda x: x),
        (
            "Quick Look extensions",
            "quicklook",
            collect(pk["quicklook_extensions"], key=lambda x: x["id"]),
            lambda x: x,
        ),
        ("Installed by a script", "scripts", {"kotlin-lsp": ["common"]}, lambda x: x),
    ]

    problems = []
    used = {group: set() for _, group, _, _ in sections}
    for _, group, entries, descriptor in sections:
        for entry in entries:
            name = descriptor(entry)
            used[group].add(name)
            if name not in (desc.get(group) or {}):
                problems.append(f"no description for {group}: {name}")
    for group, names in used.items():
        for name in (desc.get(group) or {}):
            if name not in names:
                problems.append(f"unused description in {group}: {name}")

    lines = [
        "# Tools",
        "",
        "<!-- Generated by scripts/gen-tools-doc.py from home/.chezmoidata/packages.yaml and docs/tool-descriptions.yaml.",
        "     Do not edit: change the descriptions file and run `mise run docs`. -->",
        "",
        "Everything the repo installs, from `home/.chezmoidata/packages.yaml`. Install order of preference:",
        "mise, then a Homebrew formula, then a cask, then the App Store. See [how it works](how-it-works.md).",
        "",
        "| Section | Entries |",
        "|---|---|",
    ]
    for heading, _, entries, _ in sections:
        lines.append(f"| [{heading}](#{re.sub(r'[^a-z0-9 -]', '', heading.lower()).replace(' ', '-')}) | {len(entries)} |")
    lines.append("")
    lines.append("Apps and tools installed by hand are in [manual installs](manual-installs.md).")

    for heading, group, entries, descriptor in sections:
        lines += ["", f"## {heading}", "", "| Tool | What it is | Where |", "|---|---|---|"]
        for entry in sorted(entries, key=lambda e: e.lower()):
            text = (desc.get(group) or {}).get(descriptor(entry), "?")
            lines.append(f"| `{entry}` | {text} | {where(entries[entry])} |")
    lines.append("")
    rendered = "\n".join(lines)

    if check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            problems.append("docs/tools.md is out of date: run `mise run docs`")
        if problems:
            print("\n".join(problems), file=sys.stderr)
            return 1
        print("tools doc ok")
        return 0
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({sum(len(e) for _, _, e, _ in sections)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
